import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

const fontsSourceDir = path.join(
  projectRoot,
  "node_modules",
  "@fontsource",
  "heebo",
  "files"
);

const targets = [
  { weight: 400, filename: "heebo-hebrew-400-normal.woff" },
  { weight: 700, filename: "heebo-hebrew-700-normal.woff" },
];

const chunks = targets.map(({ weight, filename }) => {
  const filePath = path.join(fontsSourceDir, filename);
  const buffer = fs.readFileSync(filePath);
  const base64 = buffer.toString("base64");
  return `export const HEEBO_${weight}_BASE64 = ${JSON.stringify(base64)};\n`;
});

const output =
  "// Auto-generated by scripts/generate-pdf-fonts.mjs — DO NOT EDIT MANUALLY.\n" +
  "// Contains Heebo Hebrew font files embedded as base64 so PDF exports never depend on filesystem access.\n\n" +
  chunks.join("\n");

const outputPath = path.join(projectRoot, "src", "lib", "pdf-fonts.ts");
fs.writeFileSync(outputPath, output, "utf8");
console.log(`Wrote embedded fonts to ${outputPath}`);
